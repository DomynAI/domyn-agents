"""Per-conversation working directories, and the Python environment inside them.

The agent gets a home in the project, like ``.git``, and each conversation gets
a directory inside it named after its id. Named after the id and not after a
timestamp so it can be found again from a transcript, a log line or a
``/conversations`` listing — a folder you cannot map back to a conversation is a
folder nobody will ever open.

    <workspace>/.domyn/conversations/<conversation_id>/
        venv/      where the agent's `pip install` goes
        output/    files it produced and may want to hand back

**The venv is the point of this module.** Without it a command inherits the
environment the CLI was launched from, and `pip install requests` lands in
whichever virtualenv is active — which, when the CLI is started with
``uv run domyn``, is *the framework's own*. An agent that can break the runtime
executing it by installing a package is a bad default, and it is not the
environment anybody thinks they are working in.

System site packages are inherited, because the alternative is worse: a bare
venv makes the agent reinstall the world before it can do anything, and most of
what it needs is already there. It sees the base interpreter's packages and
installs its own on top.

**How the venv is built matters more than it should.** ``uv venv --seed`` is
tried first, and the stdlib ``venv`` is the fallback — not the other way round.
The stdlib builder needs ``ensurepip``, and under a uv-managed interpreter that
dies with ``SIGABRT``: the standalone Python builds it installs do not carry a
working one. That failure was found the only way it could be, by watching the
first command of a session quietly run in the ambient environment while every
later one was isolated. uv is also about eight times faster here.

Creation is lazy. A conversation that never runs a command never pays for an
environment it did not use, which is most conversations.
"""

import contextlib
import os
import shutil
import subprocess
import sys
import venv
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path

from domyn.agents.logger import get_logger

# Name of the agent's home inside a project, matching the directory the CLI
# already keeps its config in.
HOME_DIRNAME = ".domyn"


def safe_id(conversation_id: str) -> str:
    """A conversation id reduced to something safe to use as a directory name.

    Public because the background-process directories need the same mapping, and
    two answers to "which folder is this conversation" is one too many.

    Ids are generated by the runner and are already tame, but they arrive from
    a caller — a gateway, a resumed session — and one containing ``../`` would
    otherwise place a venv anywhere on the disk.
    """
    cleaned = "".join(ch if ch.isalnum() or ch in "-_" else "_" for ch in conversation_id)
    return cleaned[:96] or "default"


@dataclass(frozen=True)
class SessionPaths:
    """Where one conversation keeps its things."""

    root: Path
    conversation_id: str

    @property
    def home(self) -> Path:
        return self.root / HOME_DIRNAME / "conversations" / safe_id(self.conversation_id)

    @property
    def venv(self) -> Path:
        return self.home / "venv"

    @property
    def output(self) -> Path:
        return self.home / "output"

    @property
    def python(self) -> Path:
        bindir = "Scripts" if os.name == "nt" else "bin"
        return self.venv / bindir / ("python.exe" if os.name == "nt" else "python")

    @property
    def bin(self) -> Path:
        return self.venv / ("Scripts" if os.name == "nt" else "bin")


class SessionEnvironment:
    """Builds and caches one virtualenv per conversation."""

    def __init__(self, root: Path) -> None:
        self._root = root
        self._ready: set[str] = set()

    def paths(self, conversation_id: str) -> SessionPaths:
        return SessionPaths(root=self._root, conversation_id=conversation_id)

    def prepare(self, conversation_id: str) -> SessionPaths | None:
        """Make sure the conversation's venv exists. ``None`` if it cannot.

        Returning ``None`` rather than raising: losing the isolated environment
        means commands run in the ambient one, which is how things worked
        before this existed. Refusing to run a command because a virtualenv
        could not be built would trade a small problem for a total one.
        """
        paths = self.paths(conversation_id)
        if conversation_id in self._ready:
            return paths

        try:
            paths.output.mkdir(parents=True, exist_ok=True)
            _ignore_from_version_control(paths.home.parent)
            if not paths.python.exists():
                get_logger().info(f"preparing the environment for conversation {conversation_id}")
                _create_venv(paths.venv)
        except Exception as exc:
            get_logger().warning(
                f"could not prepare an isolated environment: {type(exc).__name__}; "
                "commands will run in the ambient one"
            )
            get_logger().debug(f"session environment detail: {exc}")
            return None

        self._ready.add(conversation_id)
        return paths


def _ignore_from_version_control(conversations: Path) -> None:
    """Keep conversation directories out of the user's commits.

    They live inside the project, like ``.git`` does, which is what makes
    them findable. It also puts a virtualenv one ``git add -A`` away from being
    committed, and nobody notices until the diff is forty thousand files.
    Written once, never overwritten — if someone edited it they meant to.
    """
    marker = conversations / ".gitignore"
    if marker.exists():
        return
    with contextlib.suppress(OSError):
        marker.write_text("# Created by domyn: per-conversation working state.\n*\n")


def _create_venv(target: Path) -> None:
    """Build the virtualenv, preferring uv and falling back to the stdlib.

    Both paths must end with a usable ``pip`` inside: with the venv's ``bin``
    first on ``PATH``, a missing ``pip`` does not fail — it resolves to the next
    one along and installs somewhere else entirely, which is the exact outcome
    this module exists to prevent.
    """
    uv = shutil.which("uv")
    if uv:
        result = subprocess.run(
            [uv, "venv", "--seed", "--system-site-packages", str(target)],
            capture_output=True,
            text=True,
            check=False,
        )
        if result.returncode == 0:
            return
        get_logger().debug(f"uv venv failed ({result.returncode}): {result.stderr.strip()[:200]}")

    # Falls back with pip, then without. A venv with no pip is still better than
    # no venv: `uv pip install --python <venv>` works regardless, and the
    # isolation of everything else holds.
    try:
        venv.EnvBuilder(with_pip=True, system_site_packages=True, clear=False).create(target)
    except Exception as exc:
        get_logger().debug(f"venv with pip failed: {type(exc).__name__}: {exc}")
        venv.EnvBuilder(with_pip=False, system_site_packages=True, clear=False).create(target)
        get_logger().warning(
            f"the environment at {target} has no pip; use `uv pip install` to add packages"
        )


def environment_for(paths: SessionPaths, base: dict[str, str] | None = None) -> dict[str, str]:
    """The environment a command should see inside a conversation's venv.

    Putting the venv's ``bin`` first is not enough on its own: the launching
    virtualenv is *also* on ``PATH``, and if the CLI was started with
    ``uv run`` it comes first. Its entries are removed, or ``python`` keeps
    resolving to the runtime the agent is supposed to be isolated from.
    """
    env = dict(base if base is not None else os.environ)

    previous = env.get("VIRTUAL_ENV")
    entries = [p for p in env.get("PATH", "").split(os.pathsep) if p]
    if previous:
        previous_bin = str(Path(previous) / ("Scripts" if os.name == "nt" else "bin"))
        entries = [p for p in entries if p != previous_bin]

    env["PATH"] = os.pathsep.join([str(paths.bin), *entries])
    env["VIRTUAL_ENV"] = str(paths.venv)
    # Set by `uv run` and would send installs back to the launching project.
    env.pop("UV_PROJECT_ENVIRONMENT", None)
    # Would override the venv's own prefix and defeat the whole thing.
    env.pop("PYTHONHOME", None)
    return env


_SAFE_ENV_NAMES = frozenset(
    {
        "PATH",
        "HOME",
        "USER",
        "LOGNAME",
        "LANG",
        "LC_ALL",
        "TERM",
        "SHELL",
        "TMPDIR",
        # The CLI project the session runs in (`use_project`, interfaces/cli/config.py):
        # a folder path, not a secret, and the only way a command the agent runs —
        # `domyn skill remove`, an edit to the config — can tell which configuration
        # is in use. Absent outside a project.
        "DOMYN_PROJECT_DIR",
        # Windows equivalents.
        "SystemRoot",
        "TEMP",
        "TMP",
        "USERPROFILE",
        "APPDATA",
        "LOCALAPPDATA",
        "ComSpec",
        "PATHEXT",
    }
)


def restricted_environment(
    allowed: Iterable[str], *, base: Mapping[str, str] | None = None
) -> dict[str, str]:
    """The environment a command should see: a fixed safe set plus an explicit
    allowlist, never a raw copy of the process environment.

    Denylisting known secret names would only protect secrets from known
    sources (``.env``, ``~/.domyn/credentials``); anything the user exported
    themselves before launching ``domyn`` would still leak. Starting from
    nothing and opting names back in closes the leak regardless of where a
    secret came from.
    """
    source = base if base is not None else os.environ
    names = _SAFE_ENV_NAMES | set(allowed)
    return {name: source[name] for name in names if name in source}


def base_prefix() -> str:
    """The interpreter a conversation venv is built from, for diagnostics."""
    return sys.base_prefix
